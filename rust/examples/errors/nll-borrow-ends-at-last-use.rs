//! expect: ok
//! title: 借用はスコープの終わりではなく「最後に使った所」で終わる
//! chapter: 07-borrowing
//!
//! これは通る例。あえて置いてある。
//!
//! 2018 年より前の Rust では、借用は変数のスコープが終わるまで続くと
//! みなされていたため、これはエラーだった。いまは「最後に使った行」で
//! 借用が終わる（非語彙的ライフタイム / NLL）ので通る。
//!
//! 古い記事だけを読んでいると「Rust の借用検査は厳しすぎる」という
//! 印象が残るが、実物はここまで賢くなっている。
//! この教材はその差を、実際にコンパイルして確かめている。

fn main() {
    let mut numbers = vec![1, 2, 3];

    let first = &numbers[0];
    println!("最初の要素は {first}"); // ここで first の用は済んでいる

    numbers.push(4); // だから &mut を作れる

    println!("{numbers:?}");
}
