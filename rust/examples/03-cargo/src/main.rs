//! cargo new が作る雛形に、少しだけ手を入れたもの。
//!
//! この 1 ファイルだけで、Rust のプログラムの形が全部見えます。
//!   ・main が入口
//!   ・println! はマクロ（! が付いているのが目印）
//!   ・文の終わりにセミコロン
//!   ・ブロックの最後の式が戻り値（return を書かなくてよい）

/// 2 つの数を足す。戻り値の型は -> の後に書く。
fn add(a: i32, b: i32) -> i32 {
    a + b // セミコロンを付けない = これが戻り値
}

fn main() {
    println!("Hello, world!");

    // {} に値を差し込む。変数名を直接書ける（Rust 2021 以降）。
    let name = "Rust";
    println!("こんにちは、{name} の世界へ");

    // {:?} はデバッグ表示。中身の構造がそのまま出る。
    let numbers = [1, 2, 3];
    println!("配列をそのまま出す: {numbers:?}");

    let sum = add(2, 3);
    println!("2 + 3 = {sum}");

    // 桁を揃える、小数点以下を指定する、といった書式も使える。
    println!("円周率は {:.3}", std::f64::consts::PI);
    println!("右詰め 5 桁: [{:>5}]", 42);
}
